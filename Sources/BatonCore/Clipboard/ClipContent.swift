import Foundation

/// 剪贴板里的一份原始表示：pasteboard 类型 + 原始字节（或指向 blob 的引用）。
///
/// 一条历史记录可以有多份表示——从网页复制同时有 `public.html` 和
/// `public.utf8-plain-text`，从 Word 复制还有 `public.rtf`。全存下来，
/// 粘回去才不是纯文本。
public struct ClipContent: Sendable, Equatable, Codable {
    /// pasteboard 原始类型字符串，如 `public.rtf`
    public var type: String
    /// 非图片载荷直接进库
    public var value: Data?
    /// 图片载荷落 blob，库里只存相对路径（与 `item.blobPath` 指同一个文件）
    public var blobPath: String?

    public init(type: String, value: Data? = nil, blobPath: String? = nil) {
        self.type = type
        self.value = value
        self.blobPath = blobPath
    }
}

/// 剪贴板类型的口径集中在这里，读写两侧都用同一套常量。
public enum ClipType {
    public static let string = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let fileURL = "public.file-url"
    public static let color = "com.apple.cocoa.pasteboard.color"
    public static let tiff = "public.tiff"

    /// 图片按保真度排序：GIF 第一（带就说明要保留动画），其后是按体积常用的格式。
    /// 实际只会存第一份命中的图片类型，避免 png + tiff 双份占两倍空间。
    public static let imageCandidates: [(type: String, ext: String)] = [
        ("com.compuserve.gif", "gif"),
        ("public.png", "png"),
        ("public.heic", "heic"),
        ("public.jpeg", "jpg"),
        ("org.webmproject.webp", "webp"),
        ("public.tiff", "tiff"),
        ("com.microsoft.bmp", "bmp"),
    ]

    /// 这些类型不该落库：动态类型（每次复制都变）、Office 内部引用、WebArchive 体积巨大且不可回写。
    public static let unpersistablePrefixes = [
        "dyn.",
        "com.microsoft.ole.source.",
    ]

    public static let unpersistableExact: Set<String> = [
        "com.apple.webarchive",
        "com.apple.safari.webarchive",
        "Apple Web Archive pasteboard type",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        // 每次复制都会变的元数据/令牌：存下来会让同一条内容算出不同 hash，历史里出现重复项
        "org.nspasteboard.source",
        "x.nspasteboard.ModifiedType",
        "com.apple.linkpresentation.metadata",
        "com.apple.WebKit.custom-pasteboard-data",
        "org.chromium.web-custom-data",
        "org.chromium.source-url",
        "org.chromium.internal.source-rfh-token",
        "com.apple.notes.richtext",
        // Word 的书签/交叉引用，回写会粘出多余内容
        "com.microsoft.ObjectLink",
        "com.microsoft.Link-Source",
    ]

    /// 单份表示最大 32 MB：超出的多半是误复制的大文件/大图，存了也只会拖慢面板。
    public static let maxContentBytes = 32 * 1024 * 1024

    public static func imageExt(for type: String) -> String? {
        imageCandidates.first { $0.type == type }?.ext
    }

    public static func isImage(_ type: String) -> Bool {
        imageExt(for: type) != nil
    }

    /// 存不住的、或回写会出问题的类型。
    public static func isPersistable(_ type: String) -> Bool {
        if unpersistableExact.contains(type) { return false }
        return !unpersistablePrefixes.contains { type.hasPrefix($0) }
    }

    /// 纯文本粘贴：只留 string，文件 URL 也保留（否则「复制文件后粘路径」会坏）。
    public static func plainTextOnly(_ contents: [ClipContent]) -> [ClipContent] {
        let strings = contents.filter { $0.type == string }
        guard !strings.isEmpty else { return contents }
        return strings + contents.filter { $0.type == fileURL }
    }
}
